def mech_numbers(R, Mx):
    st_, order = Mx["stu"], R["order"]
    g = lambda s, k: float(st_[s][k])  # noqa: E731
    for s in order:
        k = KEY[s]
        define(f"mech.{k}.ntens", str(int(g(s, "PTQ_A_mm_n_tensors"))))
        for tag, col in (("mm", "PTQ_A_mm"), ("pc", "PTQ_A_pc"), ("qat", "QAT_A_mm"), ("qakdb", "QAKD_B_mm")):
            if f"{col}_acc_bb_end" in st_[s]:
                define(f"mech.{k}.bb.{tag}", dbf(g(s, f"{col}_acc_bb_end")))
            define(f"mech.{k}.bits.{tag}", num(g(s, f"{col}_bulk_bits_median"), 1))
            define(f"mech.{k}.sqmin.{tag}", num(g(s, f"{col}_sqnr_min"), 1))
            define(f"mech.{k}.rr.{tag}", num(g(s, f"{col}_range_ratio_max"), 0))
        for rule in ("mm", "pc"):
            define(f"mech.{k}.cos.{rule}", num(g(s, f"cos_own_PTQ_A_{rule}"), 2))
            define(f"mech.{k}.npown.{rule}", num(g(s, f"np_own_PTQ_A_{rule}"), 2))
        for c in ("B", "PTQ_B", "QAT_B", "QAKD_B", "QAT_A", "QAKD_A"):
            define(f"mech.{k}.npT.{c.lower().replace('_', '')}", num(g(s, f"np_T_{c}"), 2))
        for c in ("QAT_B", "QAKD_B"):
            define(f"mech.{k}.npB.{c.lower().replace('_', '')}", num(g(s, f"np_B_{c}"), 2))
        define(f"mech.{k}.npA.qata", num(g(s, "np_A_QAT_A"), 2))
        for c in ("B", "QAT_B", "QAKD_B"):
            define(f"mech.{k}.cosT.{c.lower().replace('_', '')}", num(g(s, f"cos_T_{c}"), 2))
        define(f"mech.{k}.npTregain", sgn(g(s, "np_T_QAKD_B") - g(s, "np_T_QAT_B"), 2))
        define(f"mech.{k}.npBregain", sgn(g(s, "np_B_QAKD_B") - g(s, "np_B_QAT_B"), 2))

    def rng(key, vals, d=2, signed=False):
        f = (lambda v: sgn(v, d)) if signed else (lambda v: num(v, d))
        define(f"mech.{key}.min", f(min(vals)))
        define(f"mech.{key}.max", f(max(vals)))
    rng("sqmin.mm", [g(s, "PTQ_A_mm_sqnr_min") for s in order], 1)
    rng("sqmin.pc", [g(s, "PTQ_A_pc_sqnr_min") for s in order], 1)
    rng("sqmin.qat", [g(s, "QAT_A_mm_sqnr_min") for s in order], 1)
    rng("sqmed.mm", [g(s, "PTQ_A_mm_sqnr_median") for s in order], 1)
    rng("bits.mm", [g(s, "PTQ_A_mm_bulk_bits_median") for s in order], 1)
    rng("bits.pc", [g(s, "PTQ_A_pc_bulk_bits_median") for s in order], 1)
    rng("bits.qat", [g(s, "QAT_A_mm_bulk_bits_median") for s in order], 1)
    rng("rr.mm", [g(s, "PTQ_A_mm_range_ratio_max") for s in order], 0)
    rng("rr.qat", [g(s, "QAT_A_mm_range_ratio_max") for s in order], 0)
