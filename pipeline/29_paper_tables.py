def guide_numbers(R):
    """The guide's decision variable read on the model one deploys: the distilled network after post-training
    quantization with MinMax, pair by pair, on the test and the validation fold (high-floor students against the
    others, the groups of Section 3.4)."""
    high = [s for s in R["order"] if R["mm"]["stu"][s]["PTQ_A"] >= 0.4]
    low = [s for s in R["order"] if s not in high]
    pairs = R["mm"]["pairs"]
    hi = [pairs[(s, t)]["PTQ_B"] for s in high for t in QJ.TEACHERS]
    lo = [pairs[(s, t)]["PTQ_B"] for s in low for t in QJ.TEACHERS]
    define("guide.ptqb.high.min", num(min(hi)))
    define("guide.ptqb.low.max", num(max(lo)))
    rh = [pairs[(s, t)]["PTQ_B"] / pairs[(s, t)]["B_fp32"] for s in high for t in QJ.TEACHERS]
    rl = [pairs[(s, t)]["PTQ_B"] / pairs[(s, t)]["B_fp32"] for s in low for t in QJ.TEACHERS]
    define("guide.retb.high.min", ratio(min(rh)))
    define("guide.retb.low.max", ratio(max(rl)))
    V = P.AN.load(P.path("part2", P.TAG, "eval_val.csv"), P.RULES["mm"][0], P.FT)
    vh = [V[("B", s, t, QJ.FP32_SEED)]["int8"] for s in high for t in QJ.TEACHERS]
    vl = [V[("B", s, t, QJ.FP32_SEED)]["int8"] for s in low for t in QJ.TEACHERS]
    define("guide.val.ptqb.high.min", num(min(vh)))
    define("guide.val.ptqb.low.max", num(max(vl)))
    for s in R["order"]:     # per-student means over the six teachers, for the guide table
        define(f"guide.{KEY[s]}.ptqb.test", num(st.mean(pairs[(s, t)]["PTQ_B"] for t in QJ.TEACHERS)))
        define(f"guide.{KEY[s]}.ptqb.val", num(st.mean(V[("B", s, t, QJ.FP32_SEED)]["int8"] for t in QJ.TEACHERS)))
    # what the most accurate INT8 route adds over the recommended one under percentile calibration, from the values
    # Table 3 prints (PTQ(B) for the high-floor students, QAT(B) for the others)
    pc = R["pc"]["stu"]
    cells = ("PTQ_A", "PTQ_B", "QAT_A", "QAT_B", "QAKD_A", "QAKD_B")
    for s in R["order"]:
        rec = "PTQ_B" if s in high else "QAT_B"
        best = max(cells, key=lambda c: pc[s][c])
        define(f"guide.{KEY[s]}.bestgain", sgn(round(pc[s][best], 3) - round(pc[s][rec], 3)))


