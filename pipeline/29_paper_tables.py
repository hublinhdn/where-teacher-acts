# ---------------------------------------------------------------- number formats (math minus, no dashes)
def num(x, d=3):
    return f"{x:.{d}f}"


def sgn(x, d=3):
    s = f"{x:+.{d}f}"
    if float(s) == 0:
        s = f"{0:.{d}f}"
    return f"\\ensuremath{{{s}}}"


def dbf(x, d=1):
    """A level in dB: plain digits, a math minus when negative."""
    v = round(x, d)
    return f"\\ensuremath{{{v:.{d}f}}}" if v < 0 else f"{abs(v):.{d}f}"


def ci(lo, hi, d=3):
    return f"[{sgn(lo, d)}, {sgn(hi, d)}]"


def pv(p):
    return "\\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def pct(x):
    """A whole percentage with a math minus when negative."""
    v = round(x)
    return f"\\ensuremath{{{v}}}" if v < 0 else f"{v}"


def ratio(x, d=2):
    s = f"{x:.{d}f}"
    return f"\\ensuremath{{{s}}}" if s.startswith("-") else s


