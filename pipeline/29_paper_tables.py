def _core_mix(dev):
    """The pinned phone cores by type and maximum frequency, e.g. 'two Cortex-A78 at 2.4 GHz and two Cortex-A55
    at 2.0 GHz' (the type only where the run recorded it)."""
    freqs = {int(k): int(v) for k, v in (dev.get("cpu_max_khz") or {}).items()}
    kinds = {int(k): v for k, v in (dev.get("cpu_part") or {}).items()}
    cores = [int(c) for c in dev.get("cores") or []]
    by = {}
    for c in cores:
        key = (freqs.get(c, 0), kinds.get(c, ""))
        by[key] = by.get(key, 0) + 1
    parts = [f"{WORDS[n]}{' ' + kind if kind else ''} at {f / 1e6:.1f}~GHz"
             for (f, kind), n in sorted(by.items(), reverse=True)]
    return " and ".join(parts) if parts else "four cores"


